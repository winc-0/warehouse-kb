def render(m: dict) -> str:
    """把一份手册数据渲染成 Markdown。"""
    head = [
        f"# {m['title']}",
        "",
        f"> 编号：{m['code']}　|　{'厂商' if m['kind'] == 'equipment' else '归口部门'}：{m['vendor']}　|　类别：{m['category']}",
        "",
        f"> 适用范围：{m['scope']}　|　版本：{m['version']}　|　归口：北京优速通供应链管理有限公司 运营中心",
        "",
    ]

    body = ["## 1 概述", "", m["overview"], ""]

    if m["specs"]:
        body += ["## 2 主要技术参数", "",
                 "| 参数项 | 数值 | 单位 |", "| --- | --- | --- |"]
        for name, value, unit in m["specs"]:
            body.append(f"| {name} | {value} | {unit or '—'} |")
        body.append("")

    is_sop = m["kind"] == "sop"
    extra = ENRICH.get(m["code"], {})
    faults = list(m["faults"]) + list(extra.get("faults") or [])
    maint = list(m["maint"]) + list(extra.get("maint") or [])
    cautions = list(m["cautions"]) + list(extra.get("cautions") or [])

    body += ["## 3 " + ("作业流程" if is_sop else "标准作业流程"), ""]
    body += [f"{i}. {s}" for i, s in enumerate(m["steps"], start=1)]
    body.append("")

    if faults:
        if is_sop:
            body += ["## 4 异常场景与处置", "",
                     "| 异常场景 | 判定标准 | 处置方式 |", "| --- | --- | --- |"]
        else:
            body += ["## 4 常见故障与处理", "",
                     "| 故障现象 | 可能原因 | 处理方法 |", "| --- | --- | --- |"]
        for a, b, c in faults:
            body.append(f"| {a} | {b} | {c} |")
        body.append("")

    if maint:
        if is_sop:
            body += ["## 5 关键指标与考核口径", "",
                     "| 指标 | 口径 | 目标值/频次 |", "| --- | --- | --- |"]
        else:
            body += ["## 5 维护保养计划", "",
                     "| 保养项目 | 周期 | 内容 |", "| --- | --- | --- |"]
        for a, b, c in maint:
            body.append(f"| {a} | {b} | {c} |")
        body.append("")

    body += ["## 6 " + ("执行红线" if is_sop else "安全注意事项"), ""]
    body += [f"- {c}" for c in cautions]
    body.append("")

    if extra.get("checklist"):
        body += ["## 7 现场核查清单", "",
                 "交接班与开机前逐项确认，任一项不满足不得投入作业：", ""]
        body += [f"- [ ] {c}" for c in extra["checklist"]]
        body.append("")

    body += _render_cross_ref(m, "## 8")

    body += [
        "## 9 附则",
        "",
        f"本手册由北京优速通供应链管理有限公司运营中心归口管理，"
        f"适用范围为 {m['scope']}。现场作业以本手册为准；",
        "本手册与 WMS 系统规则冲突时，以系统规则为准并及时反馈归口部门修订。",
        "各仓可根据现场条件制定实施细则，但不得低于本手册要求。",
        "",
    ]

    return "\n".join(head + body)


# 每个类别挑三个「最容易记混」的参数做横向对照。
# 这一节是刻意加的：同类多型号并存时，向量召回很容易串台，
# 语义上 CPD30 和 CPD15 的段落几乎一样，差别全在这几个数上。
COMPARE_KEYS: dict[str, list[str]] = {
    "搬运设备": ["额定载荷", "最小转弯半径", "单次充电续航"],
    "输送分拣设备": ["处理能力", "主线速度", "运行噪音"],
    "包装设备": ["电源", "整机功率", "适用膜宽"],
    "存储设备": ["层数", "单层层载", "巡检周期"],
    "冷链设备": ["制冷量", "制冷剂", "整机功率"],
    "信息系统与终端": ["通讯方式", "供电", "防护等级"],
    "作业规范": [],
}


def _spec_map(m: dict) -> dict[str, str]:
    """把 [(名称, 值, 单位)] 摊平成 {名称: 值+单位}，便于跨型号取同一参数。"""
    out = {}
    for name, value, unit in m.get("specs") or []:
        out[name] = f"{value} {unit}".strip() if unit else str(value)
    return out


def _render_cross_ref(m: dict, heading: str = "## 7") -> list[str]:
    """生成同类别设备/规范的横向对照表。"""
    cat = m["category"]
    siblings = [x for x in MANUALS if x["category"] == cat and x["code"] != m["code"]]
    if not siblings:
        return []

    keys = COMPARE_KEYS.get(cat, [])
    body = [f"{heading} 同类设备参数对照", "",
            f"本节用于选型与核对。{cat}下多型号并存，"
            f"现场最常见的错误是把相近型号的参数记混，以下对照以本手册为准。", ""]

    if not keys:
        body += ["| 编号 | 名称 | 适用范围 |", "| --- | --- | --- |"]
        body.append(f"| {m['code']} | {m['title']} | {m['scope']} |")
        for s in siblings:
            body.append(f"| {s['code']} | {s['title']} | {s['scope']} |")
        body.append("")
        return body

    body += ["| 编号 | 型号 | " + " | ".join(keys) + " |",
             "| --- | --- | " + " | ".join("---" for _ in keys) + " |"]
    for item in [m] + siblings:
        sm = _spec_map(item)
        cells = [sm.get(k, "—") for k in keys]
        short = item["title"].replace("使用手册", "").replace("使用规范", "").strip()
        body.append(f"| {item['code']} | {short} | " + " | ".join(cells) + " |")
    body.append("")
    return body


def main() -> int:
    ap = argparse.ArgumentParser(description="生成仓储物流装备与作业规范手册语料")
    ap.add_argument("--out", default=str(DEFAULT_OUT), help="输出目录")
    ap.add_argument("--only", default="", help="只生成指定类别（子串匹配）")
    args = ap.parse_args()

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    picked = [m for m in MANUALS if (not args.only or args.only in m["category"])]
    if not picked:
        print(f"[失败] 没有匹配类别：{args.only}")
        return 2

    for m in picked:
        text = render(m)
        (out / m["file"]).write_text(text, encoding="utf-8")
        print(f"  生成 {m['file']}  ({len(text)} 字符)")

    print(f"\n共 {len(picked)} 份手册 -> {out}")
    cats: dict[str, int] = {}
    for m in picked:
        cats[m["category"]] = cats.get(m["category"], 0) + 1
    for c, n in sorted(cats.items()):
        print(f"  {c}: {n}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
