PROJECT_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUT = PROJECT_ROOT / "corpus" / "warehouse"

# --------------------------------------------------------------------------- #
# 数据定义：每份手册一份
#
# 字段说明
#   code        设备编号（设备类）或规范编号（SOP 类）
#   file        输出文件名
#   title       手册标题
#   kind        equipment | sop  —— 决定渲染模板
#   vendor      厂商 / 归口部门
#   category    类别（用于分组统计）
#   scope       适用范围
#   version     版本
#   overview    概述段落
#   specs       技术参数 [(参数项, 数值, 单位)]，单位可为空字符串
#   steps       标准作业流程 [str]
#   faults      常见故障 [(现象, 原因, 处理)]
#   maint       维护保养 [(项目, 周期, 内容)]
#   cautions    安全注意事项 [str]
# --------------------------------------------------------------------------- #

MANUALS: list[dict] = []


def _eq(code, file, title, vendor, category, scope, version, overview,
        specs, steps, faults, maint, cautions):
    MANUALS.append(dict(
        kind="equipment", code=code, file=file, title=title, vendor=vendor,
        category=category, scope=scope, version=version, overview=overview,
        specs=specs, steps=steps, faults=faults, maint=maint, cautions=cautions,
    ))


def _sop(code, file, title, vendor, category, scope, version, overview,
         steps, faults, maint, cautions):
    """SOP 类没有技术参数表，steps 之外多了「关键指标」用 maint 表复用。"""
    MANUALS.append(dict(
        kind="sop", code=code, file=file, title=title, vendor=vendor,
        category=category, scope=scope, version=version, overview=overview,
        specs=[], steps=steps, faults=faults, maint=maint, cautions=cautions,
    ))


