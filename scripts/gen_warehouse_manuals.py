"""
合成「北京优速通供应链管理有限公司」仓储物流装备与作业规范手册语料。

为什么是合成语料而不是找现成的
------------------------------
这套知识库要做检索评测，评测的前提是「题库的答案确实在库里」。
用网上爬的手册有两个麻烦：一是版权与内容不可控，二是不同厂商的参数口径
互相打架，标注时无从判断哪个是正确答案。合成语料的好处是**事实由数据定义**：
下面的每一行参数既渲染进手册正文，也是后面生成标注题时的 ground truth 来源，
两者不可能对不上。

设计上刻意做了三件事，都是为了让检索有区分度（否则指标会虚高）：

1. **同类设备多型号并存**。叉车就有 CPD30 / CPD15 / R16 / BF25 四种，
   问题里只说「叉车额定载荷」是没有答案的，必须做主体确认——
   这正好压在履约知识助手链路的第一环（主体确认）上。
2. **相似的数值分散在不同设备**。起升高度 3000 / 4500 / 7500，
   转盘直径 1800，货位长 2700……向量召回很容易串台。
3. **每份手册都写清「不适用」边界**。例如摆轮分拣机不适用软包、
   流利式货架不适用纸箱。这类否定式事实最能暴露「召回成功但答错」的问题。

用法
----
    python scripts/gen_warehouse_manuals.py                 # 生成到默认目录
    python scripts/gen_warehouse_manuals.py --out D:/corpus # 指定目录
    python scripts/gen_warehouse_manuals.py --only 搬运设备  # 只生成一类（调试用）

输出每份手册一个 .md，文件名即文档标题来源（batch_import 用文件名做 file_title）。
"""

